/**
 * Import an approved bank (the workbench's export) into `@wwm/learning`: validate it against the current baseline,
 * write `packages/learning/src/banks/<objective>.json` and regenerate the registry block in `reviewed-banks.ts`.
 * Re-importing the same file changes nothing.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { type BankFile, bankFileSchema, type LearningPath, reviewedBankReport } from '@wwm/learning';

export class BankImportError extends Error {
  issues: string[];
  constructor(issues: string[]) {
    super(`The bank was not imported:\n - ${issues.join('\n - ')}`);
    this.issues = issues;
  }
}

export interface ImportResult {
  objective: string;
  /** Absolute path of the bank file. */
  file: string;
  items: number;
  /** `unchanged` when the same bank was already imported and registered. */
  status: 'written' | 'unchanged';
  flags: string[];
}

const HEADER =
  '// Generated by `pnpm learning:bank import` from the JSON files in this folder. Do not edit by hand.';

/** Formats a generated file (the CLI passes Biome, so the output passes `pnpm check`). */
export type Formatter = (source: string, file: string) => string;
const identity: Formatter = (source) => source;

/** Validate a parsed export; throws `BankImportError` listing every problem. */
export function checkBank(value: unknown, path: LearningPath): { file: BankFile; flags: string[] } {
  const parsed = bankFileSchema.safeParse(value);
  if (!parsed.success)
    throw new BankImportError(
      parsed.error.issues.map((issue) => `${issue.path.join('.') || 'file'}: ${issue.message}`),
    );
  const report = reviewedBankReport(path, parsed.data);
  if (report.issues.length) throw new BankImportError(report.issues);
  return { file: parsed.data, flags: report.flags };
}

/** `learningSrc` is `packages/learning/src`; `path` is the learning path to validate against (the baseline). */
export function importBank(
  value: unknown,
  options: { learningSrc: string; path: LearningPath; format?: Formatter },
): ImportResult {
  const { file: bank, flags } = checkBank(value, options.path);
  const dir = join(options.learningSrc, 'banks');
  mkdirSync(dir, { recursive: true });
  const file = join(dir, `${bank.objective}.json`);
  const content = (options.format ?? identity)(`${JSON.stringify(bank, null, 2)}\n`, file);
  const before = existsSync(file) ? readFileSync(file, 'utf8') : undefined;
  if (before !== content) writeFileSync(file, content);
  const registered = register(options.learningSrc, options.format);
  return {
    objective: bank.objective,
    file,
    items: bank.items.length,
    status: before === content && !registered ? 'unchanged' : 'written',
    flags,
  };
}

const camel = (id: string) => id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

/** Regenerate `banks/index.ts` from the JSON files in `banks/`. Returns true if it changed. */
export function register(learningSrc: string, format: Formatter = identity): boolean {
  const dir = join(learningSrc, 'banks');
  const index = join(dir, 'index.ts');
  const objectives = readdirSync(dir)
    .filter((name) => /^[a-z][a-z0-9-]*\.json$/.test(name))
    .map((name) => name.slice(0, -'.json'.length))
    .sort();
  const imports = objectives.map(
    (objective) => `import ${camel(objective)} from './${objective}.json' with { type: 'json' };`,
  );
  const source = format(
    [
      HEADER,
      ...imports,
      ...(imports.length ? [''] : []),
      `export const bankFiles: unknown[] = [${objectives.map(camel).join(', ')}];`,
      '',
    ].join('\n'),
    index,
  );
  if (existsSync(index) && readFileSync(index, 'utf8') === source) return false;
  writeFileSync(index, source);
  return true;
}
