import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { type BankFile, baselinePath, spellingBankRound, spellingVocabulary } from '@wwm/learning';
import { describe, expect, test } from 'vitest';
import { BankImportError, checkBank, importBank, register } from '../src/bank-import.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '../../..');
const entry = (word: string) =>
  spellingVocabulary.words.find((candidate) => candidate.word === word) ?? { word, meaning: 'x' };
const item = (id: string, word: string) =>
  spellingBankRound(id, entry(word), 1, [word[1]?.toUpperCase() ?? '', 'Y']);

function file(
  items: BankFile['items'] = [item('i-000000000001', 'pig'), item('i-000000000002', 'hen')],
): BankFile {
  return {
    format: 'wwm-learning-bank/1',
    objective: 'little-word-builders',
    items,
    provenance: {
      draft: 'd-00000000-0000-4000-8000-000000000000',
      revision: '0123456789abcdef0123456789abcdef',
      approvedAt: '2026-10-19T12:00:00.000Z',
      note: 'Checked.',
      model: 'claude-sonnet-5-5',
      vocabulary: 'en-cvc-starter',
    },
  };
}
const scratch = () => mkdtempSync(join(tmpdir(), 'wwm-learning-src-'));
const issues = (fn: () => unknown) => {
  try {
    fn();
  } catch (error) {
    if (error instanceof BankImportError) return error.issues.join('\n');
    throw error;
  }
  return '';
};

describe('pnpm learning:bank import', () => {
  test('writes the bank file and registers it; a second import changes nothing', () => {
    const learningSrc = scratch();
    const first = importBank(file(), { learningSrc, path: baselinePath });
    expect(first).toMatchObject({ status: 'written', objective: 'little-word-builders', items: 2 });
    expect(JSON.parse(readFileSync(join(learningSrc, 'banks/little-word-builders.json'), 'utf8'))).toEqual(
      file(),
    );
    expect(readFileSync(join(learningSrc, 'banks/index.ts'), 'utf8')).toBe(
      [
        '// Generated by `pnpm learning:bank import` from the JSON files in this folder. Do not edit by hand.',
        "import littleWordBuilders from './little-word-builders.json' with { type: 'json' };",
        '',
        'export const bankFiles: unknown[] = [littleWordBuilders];',
        '',
      ].join('\n'),
    );
    expect(importBank(file(), { learningSrc, path: baselinePath }).status).toBe('unchanged');
    // A newer approved bank for the objective replaces the file.
    expect(
      importBank(file([item('i-000000000003', 'bus')]), { learningSrc, path: baselinePath }).status,
    ).toBe('written');
  });

  test('the generated registry with no banks matches the committed one', () => {
    const learningSrc = scratch();
    mkdirSync(join(learningSrc, 'banks'));
    register(learningSrc);
    expect(readFileSync(join(learningSrc, 'banks/index.ts'), 'utf8')).toBe(
      readFileSync(join(root, 'packages/learning/src/banks/index.ts'), 'utf8'),
    );
  });

  test.each([
    ['not an export', { objective: 'little-word-builders', items: [] }, 'format'],
    ['an unknown objective', { ...file(), objective: 'flying-lessons' }, 'Unknown objective'],
    ['a generator objective', { ...file(), objective: 'compare-groups' }, 'already has a generator bank'],
    ['an invalid round', { ...file(), items: [{ ...item('a', 'pig'), answer: 'q' }] }, 'items'],
    [
      'a duplicate item',
      file([item('i-000000000001', 'pig'), item('i-000000000002', 'pig')]),
      'duplicates another item',
    ],
    [
      'a lesson repeat',
      file([
        {
          ...(baselinePath.activities.find((a) => a.id === 'little-word-builders')
            ?.rounds[1] as BankFile['items'][number]),
          id: 'i-1',
        },
      ]),
      'repeats a round in the lesson',
    ],
    [
      'a word off the list',
      file([{ ...item('a', 'pig'), stimulusText: 'Z _ G', practice: { text: 'Zig', language: 'en-US' } }]),
      'not on the reviewed word list',
    ],
    ['a stray field', { ...file(), approvedBy: 'someone@example.com' }, 'Unrecognized key'],
  ])('refuses %s and writes nothing', (_name, value, message) => {
    const learningSrc = scratch();
    expect(issues(() => importBank(value, { learningSrc, path: baselinePath }))).toContain(message);
    expect(existsSync(join(learningSrc, 'banks'))).toBe(false);
  });

  test('check validates without writing and lists reviewer flags', () => {
    const map = spellingBankRound('i-000000000001', entry('map'), 2, ['P', 'T']);
    const { flags } = checkBank(file([map]), baselinePath);
    expect(flags.join(' ')).toContain('"MAP" is also in the lesson');
    expect(flags.join(' ')).toContain('Distractor also spells a real word (MAT)');
  });

  test('the CLI formats what it writes so pnpm check stays green', () => {
    const learningSrc = scratch();
    const input = join(learningSrc, 'export.json');
    writeFileSync(input, JSON.stringify(file()));
    const biome = join(root, 'node_modules/.bin/biome');
    const format = (source: string, path: string) =>
      execFileSync(
        biome,
        [
          'format',
          `--stdin-file-path=${join(root, 'packages/learning/src/banks', path.split('/').at(-1) ?? '')}`,
        ],
        {
          cwd: root,
          input: source,
          encoding: 'utf8',
        },
      );
    importBank(file(), { learningSrc, path: baselinePath, format });
    const json = readFileSync(join(learningSrc, 'banks/little-word-builders.json'), 'utf8');
    expect(format(json, 'little-word-builders.json')).toBe(json);
    expect(JSON.parse(json)).toEqual(file());
  });
});
